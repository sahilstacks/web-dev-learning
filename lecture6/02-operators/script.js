let score = 28;
console.log("Score:", score);
console.log("data-type of score:", typeof score);

// Arithmetic Operators
console.log("Score + 2:", score + 2);
console.log("Score - 2:", score - 2);
console.log("Score * 2:", score * 2);
console.log("Score / 2:", score / 2);
console.log("Score % 2:", score % 2);

// Comparison Operators
console.log("Score == 28:", score == 28);
console.log("Score === 28:", score === "28");
console.log("Score != 28:", score != 28);
console.log("Score > 28:", score > 28);
console.log("Score < 28:", score < 28);
console.log("Score >= 28:", score >= 28);
console.log("Score <= 28:", score <= 28);

// Logical Operators
console.log("Score > 20 && Score < 30:", score > 20 && score < 30);
console.log("Score < 20 || Score > 30:", score < 20 || score > 30);
console.log("!(Score == 28):", !(score == 28));